# ---------------------------------------------------------------- WP9 permissions

def test_permission_chain_allow_and_deny(project, run_py):
    run_py(project, "orchestrator.py", "--status")
    code, out = run_py(project, "guard.py", "--permission", "read-only", "--check",
                       "implement the login endpoint in src with input validation")
    assert code == 0 and "ALLOWED" in out
    code, out = run_py(project, "guard.py", "--permission", "read-only", "--check",
                       "I plan to run npm install then git push")
    assert code == 126 and "DENIED" in out


def test_permission_unknown_mode_rejected(project, run_py):
    run_py(project, "orchestrator.py", "--status")
    # argparse rejects an unknown mode up front (fail-closed, exit != 0)
    code, out = run_py(project, "guard.py", "--permission", "bogus", "--check", "x")
    assert code != 0 and "invalid choice" in out


def test_enforce_permission_exit_code_separation(project, run_py):
    code, out = run_py(project, "tools/enforce-permission.py", "--mode", "read-only",
                       "--", sys.executable, "-c", "print('hi')")
    assert code == 0
    code, out = run_py(project, "tools/enforce-permission.py", "--mode", "read-only",
                       "--", "pip", "install", "flask")
    assert code == 126 and "PERMISSION_DENIED" in out
    # task failure is NOT a permission denial
    code, out = run_py(project, "tools/enforce-permission.py", "--mode", "full",
                       "--", sys.executable, "-c", "import sys; sys.exit(3)")
    assert code == 3


