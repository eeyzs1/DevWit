def test_skill_catalog_list_and_load(project, run_py):
    skills_dir = project / "skills"
    skills_dir.mkdir()
    (skills_dir / "systematic-debugging.md").write_text(
        "# Systematic Debugging\n\nRoot cause first.\n", encoding="utf-8")
    (skills_dir / "tdd.md").write_text("# TDD\n\nWrite tests first.\n", encoding="utf-8")
    # catalog generated by scaffold in real projects; test the loader directly
    catalog = {"version": 1, "complete": True, "skills": [
        {"id": "systematic-debugging", "name": "Systematic Debugging",
         "description": "Root cause first.", "path": "skills/systematic-debugging.md"},
        {"id": "tdd", "name": "TDD", "description": "Write tests first.",
         "path": "skills/tdd.md"},
    ]}
    import yaml
    (skills_dir / "catalog.yaml").write_text(yaml.dump(catalog), encoding="utf-8")

    code, out = run_py(project.parent, str(HARNESS_ROOT / "seeds" / "context" / "loader.py"),
                       "skill", "list", "--project-root", str(project))
    assert code == 0 and "systematic-debugging" in out
    code, out = run_py(project.parent, str(HARNESS_ROOT / "seeds" / "context" / "loader.py"),
                       "skill", "load", "tdd", "--project-root", str(project))
    assert code == 0 and "Write tests first" in out
    code, out = run_py(project.parent, str(HARNESS_ROOT / "seeds" / "context" / "loader.py"),
                       "skill", "load", "nope", "--project-root", str(project))
    assert code == 2 and "unknown skill" in out


